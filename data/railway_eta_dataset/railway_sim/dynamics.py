"""
Core generative model for section-level running time / delay.

This is the ONE place that decides "what happens on this section, on this
date, for this train". Both generate_historical_dataset.py (bulk offline
generation) and live_feed_simulator.py (streaming simulation) call
`simulate_section()` from this module, so a model trained on the historical
CSV sees data generated by the exact same process as the "live" feed used
to demo it. That consistency is the whole point of building this instead of
grabbing an unrelated public CSV.

Calibration notes (so the numbers aren't arbitrary):
- Average arrival delay across Indian Railways has been reported around
  ~30 minutes in a 2023 industry punctuality analysis, and around ~51
  minutes in a September 2024 nationwide academic dataset (RSTGCN paper,
  arXiv 2510.01262) that also names congestion, asset failures, external
  factors (fog, law & order) and infrastructure works as the four broad
  delay causes -- language taken directly from Ministry of Railways'
  own Parliament answers. Fog, in particular, is a well-documented,
  season-specific driver of severe (multi-hour) delay on northern routes
  in Dec-Feb.
- The generator below reproduces that qualitative shape: mostly modest
  delay, a heavier tail from congestion, and occasional severe fog/TSR
  events -- rather than a single tidy Gaussian.
"""

import random
import math
from dataclasses import dataclass
from datetime import date, datetime, timedelta

# Simple fixed holiday/festival-season windows (illustrative, not exhaustive).
# Extra dwell time + slightly higher congestion around these.
FESTIVAL_WINDOWS = [
    (date(2000, 10, 15), date(2000, 11, 15)),  # Durga Puja / Diwali season (month-day matched, year ignored)
    (date(2000, 3, 1), date(2000, 3, 20)),      # Holi season
]


def _month_day_in_window(d: date, start: date, end: date) -> bool:
    md = (d.month, d.day)
    s, e = (start.month, start.day), (end.month, end.day)
    return s <= md <= e


def is_festival_season(d: date) -> bool:
    return any(_month_day_in_window(d, s, e) for s, e in FESTIVAL_WINDOWS)


def season_of(d: date) -> str:
    if d.month in (12, 1, 2):
        return "winter"
    if d.month in (6, 7, 8, 9):
        return "monsoon"
    return "other"


@dataclass
class SectionOutcome:
    weather_condition: str
    visibility_m: int
    temperature_c: float
    is_tsr: bool
    tsr_effective_speed_kmph: int
    added_delay_min: float
    recovered_min: float
    extra_halt_overstay_min: float


def _fog_event(rng: random.Random, section, d: date, departure_hour: int) -> SectionOutcome:
    """Fog only matters in winter, on fog-prone sections, in early-morning /
    late-night hours -- matching real Indian Railways fog-delay patterns."""
    season = season_of(d)
    fog_hours = departure_hour <= 8 or departure_hour >= 22
    fog_chance = 0.35 if (section.fog_prone and season == "winter" and fog_hours) else \
                 (0.08 if (section.fog_prone and season == "winter") else 0.0)
    if rng.random() < fog_chance:
        severity = rng.random()
        visibility = int(rng.uniform(30, 400) * (1 - severity * 0.5))
        # severe fog can add well over an hour; matches documented patterns
        added_delay = rng.uniform(15, 40) + severity * rng.uniform(20, 140)
        return "fog", max(20, visibility), added_delay
    return None


def _rain_event(rng: random.Random, section, d: date) -> "tuple|None":
    season = season_of(d)
    if season != "monsoon":
        return None
    base_chance = 0.18 if section.terrain == "coastal" else 0.10
    if rng.random() < base_chance:
        intensity = rng.random()
        added_delay = rng.uniform(5, 20) + intensity * rng.uniform(10, 60)
        return "heavy_rain" if intensity > 0.6 else "light_rain", added_delay
    return None


def _congestion_delay(rng: random.Random, section, departure_hour: int) -> float:
    peak = departure_hour in (6, 7, 8, 9, 17, 18, 19, 20, 21)
    base = rng.gammavariate(2.3, 6.5) * (0.5 + section.congestion_level)
    if peak:
        base *= 1.6
    return base


def _tsr_event(rng: random.Random, section) -> "tuple|None":
    # Localised temporary speed restriction: track work, minor asset issue.
    if rng.random() < 0.035:
        eff_speed = int(section.permissible_speed_kmph * rng.uniform(0.35, 0.6))
        extra_time_min = section.distance_km * (60.0 / eff_speed - 60.0 / section.permissible_speed_kmph)
        return True, eff_speed, max(3.0, extra_time_min)
    return None


def simulate_section(rng: random.Random, section, train, journey_date: date,
                      scheduled_departure_dt: datetime, incoming_delay_min: float):
    """
    Returns a dict describing what happened on this section:
    weather, TSR, congestion, recovered slack, and the resulting
    arrival_delay_min / departure_delay_min / actual_running_min.
    """
    departure_hour = scheduled_departure_dt.hour
    weather_condition = "clear"
    visibility_m = 8000
    added_delay = 0.0

    fog = _fog_event(rng, section, journey_date, departure_hour)
    if fog:
        weather_condition, visibility_m, fog_delay = fog
        added_delay += fog_delay
    else:
        rain = _rain_event(rng, section, journey_date)
        if rain:
            weather_condition, rain_delay = rain
            added_delay += rain_delay

    added_delay += _congestion_delay(rng, section, departure_hour)

    tsr = _tsr_event(rng, section)
    is_tsr, tsr_speed = False, section.permissible_speed_kmph
    if tsr:
        is_tsr, tsr_speed, tsr_delay = tsr
        added_delay += tsr_delay

    # small ambient noise (crew/signal micro-variation)
    added_delay += rng.gauss(0, 2.5)
    added_delay = max(0.0, added_delay)

    # recovery: express/priority trains can claw back some incoming delay
    # using built-in schedule slack; passenger trains have little slack.
    max_recoverable = section.scheduled_min * train.recovery_fraction
    recovered = min(incoming_delay_min, max_recoverable * rng.uniform(0.4, 1.0)) \
        if incoming_delay_min > 0 else 0.0

    departure_delay_prev = incoming_delay_min  # delay at departure from previous stn

    # festival dwell overstay (only affects the HALT at the destination of
    # this section, applied by the caller when computing next departure)
    extra_halt_overstay = 0.0
    if is_festival_season(journey_date):
        extra_halt_overstay = section.halt_min_at_to * rng.uniform(0.1, 0.6)

    arrival_delay = max(0.0, departure_delay_prev - recovered + added_delay)
    actual_running_min = section.scheduled_min + (arrival_delay - departure_delay_prev)
    avg_speed_kmph = section.distance_km / (actual_running_min / 60.0) if actual_running_min > 0 else section.permissible_speed_kmph
    temperature_c = _synthetic_temperature(section, journey_date, rng)

    # Anomaly should flag "slower than this section's own normal running
    # speed", not "slower than the sanctioned top speed" -- a section's
    # scheduled speed is already well below its permissible ceiling because
    # of curves/gradients/halts, so comparing to the ceiling flags almost
    # every normal run. Compare to the section's own SCHEDULED average
    # speed instead; this is what would let a live system infer a TSR or
    # congestion event from GPS speed alone, without an official TSR feed.
    scheduled_avg_speed_kmph = section.distance_km / (section.scheduled_min / 60.0)
    speed_anomaly = avg_speed_kmph < 0.65 * scheduled_avg_speed_kmph

    return {
        "weather_condition": weather_condition,
        "visibility_m": visibility_m,
        "temperature_c": round(temperature_c, 1),
        "is_tsr": is_tsr,
        "tsr_effective_speed_kmph": tsr_speed if is_tsr else None,
        "arrival_delay_min": round(arrival_delay, 1),
        "actual_running_min": round(actual_running_min, 1),
        "avg_speed_kmph": round(avg_speed_kmph, 1),
        "recovered_min": round(recovered, 1),
        "extra_halt_overstay_min": round(extra_halt_overstay, 1),
        "scheduled_avg_speed_kmph": round(scheduled_avg_speed_kmph, 1),
        "speed_anomaly": speed_anomaly,
    }


def _synthetic_temperature(section, d: date, rng: random.Random) -> float:
    season = season_of(d)
    base = {"winter": 16.0, "monsoon": 27.0, "other": 30.0}[season]
    # rough north/south adjustment using latitude of the "to" station
    from .network import STATIONS
    lat = STATIONS[section.to_code].lat
    base += (20 - lat) * 0.3
    return base + rng.gauss(0, 3.0)
