#!/usr/bin/env python3
"""
Streams a single train's journey as a sequence of GPS-ping-like JSON events,
generated by the SAME dynamics model used to build the historical training
CSV (railway_sim/dynamics.py). This is what you point your live ETA-serving
pipeline at during development/demo, before wiring up a real RTIS/COA feed.

Two ways to use it:

1) As a library, inside your own ETA service / notebook:

    from live_feed_simulator import simulate_journey_events
    for event in simulate_journey_events("12951", date(2025, 12, 20), seed=7):
        handle_event(event)   # feed into your ETA re-forecasting logic

2) As a CLI that prints JSON-lines to stdout, at accelerated playback speed
   (useful for a live-look dashboard demo):

    python3 live_feed_simulator.py --train 12951 --date 2025-12-20 \
        --speed 240 --pings-per-section 6

   --speed 240 means 240x real time (a ~4-hour section replays in ~1 minute).

Event types emitted:
  "departure"  - train departs a station (includes scheduled vs actual)
  "position"   - a GPS-like ping while in transit between two stations
  "arrival"    - train arrives at a station (includes the delay outcome)

Each event carries a `live_eta_next_station_min` field: a simple estimate of
minutes-to-next-station, linearly interpolating between the outcome computed
for that section. A real ETA model should replace this with its own
prediction -- these events are the INPUT stream, not the model output.
"""

import argparse
import json
import random
import time
from datetime import date, datetime, timedelta

from railway_sim.network import STATIONS, sections_for_route
from railway_sim.schedule import build_train_schedule, ORIGIN_DEPARTURE_TIME
from railway_sim.dynamics import simulate_section
from railway_sim.network import TRAINS


def _train_by_no(train_no):
    for t in TRAINS:
        if t.train_no == train_no:
            return t
    raise ValueError(f"Unknown train_no {train_no}")


def _interp(a, b, frac):
    return a + (b - a) * frac


def simulate_journey_events(train_no: str, journey_date: date, seed: int = None,
                             pings_per_section: int = 6):
    """Generator yielding dict events for one full journey."""
    rng = random.Random(seed)
    train = _train_by_no(train_no)
    secs = sections_for_route(train.route_id)
    schedule = build_train_schedule(train)
    oh, om = map(int, ORIGIN_DEPARTURE_TIME[train_no].split(":"))
    origin_dt = datetime(journey_date.year, journey_date.month, journey_date.day, oh, om)

    incoming_delay = 0.0
    cur_dt = origin_dt

    yield {
        "event": "departure", "train_no": train_no, "station": schedule[0]["station_code"],
        "scheduled_time": origin_dt.isoformat(), "actual_time": cur_dt.isoformat(),
        "delay_min": 0.0,
    }

    for i, sec in enumerate(secs):
        stop = schedule[i + 1]
        dep_dt = origin_dt + timedelta(minutes=schedule[i]["scheduled_departure_min"])
        outcome = simulate_section(rng, sec, train, journey_date, dep_dt, incoming_delay)

        from_st, to_st = STATIONS[sec.from_code], STATIONS[sec.to_code]
        section_minutes = outcome["actual_running_min"]

        for p in range(1, pings_per_section + 1):
            frac = p / (pings_per_section + 1)
            ping_time = cur_dt + timedelta(minutes=section_minutes * frac)
            lat = _interp(from_st.lat, to_st.lat, frac)
            lon = _interp(from_st.lon, to_st.lon, frac)
            eta_next_min = round(section_minutes * (1 - frac), 1)
            yield {
                "event": "position",
                "train_no": train_no,
                "timestamp": ping_time.isoformat(),
                "lat": round(lat, 5), "lon": round(lon, 5),
                "between": [sec.from_code, sec.to_code],
                "fraction_of_section_complete": round(frac, 2),
                "current_speed_kmph": round(outcome["avg_speed_kmph"] * rng.uniform(0.85, 1.15), 1),
                "speed_anomaly_flag": outcome["speed_anomaly"],
                "weather_condition": outcome["weather_condition"],
                "estimated_delay_so_far_min": round(_interp(incoming_delay, outcome["arrival_delay_min"], frac), 1),
                "live_eta_next_station_min": eta_next_min,
            }

        cur_dt = cur_dt + timedelta(minutes=section_minutes)
        yield {
            "event": "arrival",
            "train_no": train_no,
            "station": sec.to_code,
            "scheduled_time": (origin_dt + timedelta(minutes=stop["scheduled_arrival_min"])).isoformat(),
            "actual_time": cur_dt.isoformat(),
            "delay_min": outcome["arrival_delay_min"],
            "weather_condition": outcome["weather_condition"],
            "is_tsr_event": outcome["is_tsr"],
        }

        if sec.halt_min_at_to > 0:
            dep_time = cur_dt + timedelta(minutes=sec.halt_min_at_to + outcome["extra_halt_overstay_min"])
            yield {
                "event": "departure",
                "train_no": train_no,
                "station": sec.to_code,
                "scheduled_time": (origin_dt + timedelta(minutes=stop["scheduled_departure_min"])).isoformat(),
                "actual_time": dep_time.isoformat(),
                "delay_min": outcome["arrival_delay_min"] + outcome["extra_halt_overstay_min"],
            }
            cur_dt = dep_time

        incoming_delay = outcome["arrival_delay_min"] + outcome["extra_halt_overstay_min"]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--train", required=True, help="train_no, e.g. 12951")
    ap.add_argument("--date", required=True, help="journey date YYYY-MM-DD")
    ap.add_argument("--seed", type=int, default=None)
    ap.add_argument("--speed", type=float, default=120.0, help="playback speed multiplier (real-time seconds compressed)")
    ap.add_argument("--pings-per-section", type=int, default=6)
    ap.add_argument("--out", type=str, default=None, help="optional: write JSON-lines to this file instead of only stdout")
    args = ap.parse_args()

    jdate = datetime.strptime(args.date, "%Y-%m-%d").date()
    events = simulate_journey_events(args.train, jdate, seed=args.seed,
                                      pings_per_section=args.pings_per_section)

    out_f = open(args.out, "w") if args.out else None
    prev_wall = None
    prev_sim = None
    for ev in events:
        line = json.dumps(ev)
        print(line)
        if out_f:
            out_f.write(line + "\n")

        sim_time = datetime.fromisoformat(ev.get("timestamp") or ev.get("actual_time"))
        if prev_sim is not None:
            gap_sec = (sim_time - prev_sim).total_seconds() / args.speed
            if gap_sec > 0:
                time.sleep(min(gap_sec, 2.0))  # cap sleep for CLI usability
        prev_sim = sim_time

    if out_f:
        out_f.close()


if __name__ == "__main__":
    main()
